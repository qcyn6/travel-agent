def _province_aliases(name: str) -> set[str]:
    aliases = {name}
    short = _PROVINCE_SHORT_ALIASES.get(name)
    if short:
        aliases.add(short)
    for suffix in ("特别行政区", "自治区", "省", "市"):
        if name.endswith(suffix):
            aliases.add(name[: -len(suffix)])
    return {item for item in aliases if item}


