def city_coordinate_anchor(
    *,
    city_name: str,
    province_name: str,
    observed_coordinates: list[tuple[float, float]],
) -> tuple[float, float]:
    """Choose an anchor from existing POIs, then local city/province knowledge."""

    if observed_coordinates:
        return (
            float(median(item[0] for item in observed_coordinates)),
            float(median(item[1] for item in observed_coordinates)),
        )
    if city_name in CITY_CENTER_COORDINATES:
        return CITY_CENTER_COORDINATES[city_name]
    return PROVINCE_CENTER_COORDINATES.get(province_name, (105.0, 35.0))


def coordinate_for_attraction(
    *,
    poi_id: str,
    name: str,
    city_name: str,
    province_name: str,
    anchor: tuple[float, float],
) -> tuple[float, float]:
    """Return a stable approximate coordinate for a missing POI location."""

    for keyword, coordinate in KNOWN_ATTRACTION_COORDINATES:
        if keyword in name:
            return coordinate

    digest = hashlib.sha256(f"{poi_id}|{city_name}|{name}".encode("utf-8")).digest()
    horizontal = int.from_bytes(digest[:2], "big") / 65535.0 - 0.5
    vertical = int.from_bytes(digest[2:4], "big") / 65535.0 - 0.5
    spread = 0.012
    if _contains(
        name,
        (
            "风景区",
            "风景名胜",
            "国家公园",
            "自然保护区",
            "草原",
            "峡谷",
            "雪山",
            "海岛",
            "度假区",
        ),
    ):
        spread = 0.055
    longitude, latitude = anchor
    return (
        round(longitude + horizontal * spread, 6),
        round(latitude + vertical * spread, 6),
    )


