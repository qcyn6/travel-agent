def _contains(text: str, keywords: tuple[str, ...]) -> bool:
    return any(keyword in text for keyword in keywords)


def infer_attraction_category(name: str, raw_category: str | None = None) -> str:
    """Map a POI name to one stable display/planning category."""

    name_text = str(name or "").strip()
    for category, keywords in _CATEGORY_OVERRIDES:
        if _contains(name_text, keywords):
            return category

    # Prefer the more specific ecology/urban/resort buckets before the broad
    # water and mountain rules below.  For example, a wetland park is not
    # merely a river attraction and a hot-spring resort is not just a spring.
    if _contains(
        name_text,
        (
            "湿地",
            "森林公园",
            "国家森林",
            "国家公园",
            "自然保护区",
            "植物园",
            "动物园",
            "野生动物",
            "花海",
            "生态园",
            "园博园",
            "花卉",
            "花博园",
        ),
    ):
        return "生态动植物"
    if _contains(name_text, ("公园", "广场", "绿道", "城市绿地", "滨江带")) and not _contains(
        name_text,
        ("古城", "古镇", "古村", "遗址", "故居", "古迹", "长城", "纪念园"),
    ):
        return "城市公园"
    if _contains(name_text, ("度假", "温泉", "滑雪", "露营", "康养", "房车", "高尔夫")):
        return "休闲度假"
    for category, keywords in _CATEGORY_RULES:
        if _contains(name_text, keywords):
            return category

    # Provider categories are only a fallback.  This avoids allowing the
    # former broad "自然风光" value to misclassify a named museum or temple.
    raw_text = str(raw_category or "").strip()
    for category, keywords in _CATEGORY_RULES:
        if _contains(raw_text, keywords):
            return category
    return "综合景区"


