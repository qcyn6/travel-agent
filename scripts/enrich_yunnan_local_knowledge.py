def _serialise(value):
    if isinstance(value, datetime):
        return value.isoformat()
    return value


def _backup_rows(rows: list[AttractionRow]) -> dict:
    return {
        "created_at": datetime.now().isoformat(),
        "reason": "yunnan-local-knowledge-enrichment",
        "rows": [
            {
                column.name: _serialise(getattr(attraction, column.name))
                for column in attraction.__table__.columns
            }
            for attraction in rows
        ],
    }


def run(*, commit: bool, backup_dir: Path) -> int:
    if len(LOCAL_KNOWLEDGE) != 70:
        raise RuntimeError(f"本地知识 manifest 应有 70 条，当前为 {len(LOCAL_KNOWLEDGE)} 条")
    poi_ids = [item.poi_id for item in LOCAL_KNOWLEDGE]
    if len(set(poi_ids)) != len(poi_ids):
        raise RuntimeError("本地知识 manifest 存在重复 poi_id")

    init_database()
    with open_session() as session:
        rows: list[tuple[AttractionRow, CityRow]] = []
        missing: list[str] = []
        wrong_city: list[str] = []
        for item in LOCAL_KNOWLEDGE:
            result = session.execute(
                select(AttractionRow, CityRow)
                .join(CityRow, CityRow.id == AttractionRow.city_id)
                .join(ProvinceRow, ProvinceRow.id == CityRow.province_id)
                .where(
                    AttractionRow.poi_id == item.poi_id,
                    ProvinceRow.name == "云南省",
                )
            ).first()
            if result is None:
                missing.append(item.poi_id)
                continue
            attraction, city = result
            if city.name != item.city:
                wrong_city.append(f"{item.poi_id}: manifest={item.city}, db={city.name}")
                continue
            rows.append((attraction, city))

        if missing or wrong_city:
            if missing:
                print("数据库中找不到云南 POI：" + ", ".join(missing))
            if wrong_city:
                print("城市归属不一致：" + "; ".join(wrong_city))
            return 1

        counts: dict[str, int] = {}
        for item in LOCAL_KNOWLEDGE:
            counts[item.city] = counts.get(item.city, 0) + 1
        print(
            f"matched rows: {len(rows)} | "
            + ", ".join(f"{city}={count}" for city, count in counts.items())
        )
        for item in LOCAL_KNOWLEDGE[:10]:
            print(f"- {item.poi_id}: {item.category} | {item.visit_duration_minutes} min")

        if not commit:
            print("preview only; pass --commit to update MySQL")
            return 0

        backup_dir.mkdir(parents=True, exist_ok=True)
        backup_path = backup_dir / (
            "yunnan-local-knowledge-before-enrichment-"
            f"{datetime.now().strftime('%Y%m%d-%H%M%S')}.json"
        )
        backup_path.write_text(
            json.dumps(
                _backup_rows([attraction for attraction, _city in rows]),
                ensure_ascii=False,
                indent=2,
                default=str,
            ),
            encoding="utf-8",
        )

        by_poi_id = {item.poi_id: item for item in LOCAL_KNOWLEDGE}
        for attraction, _city in rows:
            item = by_poi_id[attraction.poi_id]
            attraction.category = item.category
            attraction.tags = list(item.tags)
            attraction.description = item.description
            attraction.visit_duration_minutes = item.visit_duration_minutes
            if item.coordinate is not None:
                attraction.longitude, attraction.latitude = item.coordinate

        session.commit()
        print(f"committed: {len(rows)}")
        print(f"backup: {backup_path}")
    return 0


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--commit", action="store_true", help="写入 MySQL；默认只预览")
    parser.add_argument(
        "--backup-dir",
        default=str(ROOT / "data" / "backups"),
        help="受影响记录的备份目录",
    )
    args = parser.parse_args()
    raise SystemExit(run(commit=args.commit, backup_dir=Path(args.backup_dir)))


if __name__ == "__main__":
    main()
