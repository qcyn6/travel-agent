"""Replace province profile prose with bounded public encyclopedia summaries.

This is a source-backed pass for the 34 province-level rows.  It leaves the
database schema and administrative names/codes unchanged.  Preview mode is
the default; ``--commit`` writes a backup, updates MySQL, and generates the
static override consumed by ``backend.database.catalog`` so the next seed
does not restore the old template prose.  No Amap endpoint is used.
"""

from __future__ import annotations

import argparse
from datetime import datetime
import html
import json
from pathlib import Path
import re
import sys
from urllib.parse import quote

import requests
from sqlalchemy import select

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.database import init_database, open_session  # noqa: E402
from backend.database.tables import ProvinceRow  # noqa: E402


API_URL = "https://baike.baidu.com/api/openapi/BaikeLemmaCardApi"
USER_AGENT = "travel-agent-public-source-audit/1.0"
CACHE_PATH = ROOT / "data" / "destination_sources" / "province_baike_cache.json"
OVERRIDE_PATH = ROOT / "backend" / "database" / "province_profiles.py"
BACKUP_DIR = ROOT / "data" / "backups"
MIN_TEXT_LENGTH = 24
MAX_TEXT_LENGTH = 280


def _clean(value: str) -> str:
    value = html.unescape(re.sub(r"<[^>]+>", "", value or ""))
    value = re.sub(r"\[[0-9]+\]", "", value)
    value = re.sub(r"\s+", "", value)
    return value.strip()


def _normalise(value: str) -> str:
    return re.sub(r"[\s\-—－·•/｜|（）()【】\[\]，,。:：]", "", value).lower()


def _stable_summary(abstract: str, desc: str, name: str) -> str | None:
    """Keep stable introductory facts and drop volatile statistics."""
    source = _clean(abstract) or _clean(desc)
    if not source:
        return None
    # Avoid copying population/area and current-year administrative statistics
    # into a long-lived travel profile.
    source = re.split(r"(?:截至|目前|其中|202[0-9]年|20[0-9]{2}年|人口|总?面积)", source, maxsplit=1)[0]
    source = re.sub(r"（[^（）]*[A-Za-z][^（）]*）", "", source)
    source = source.replace("英文名，", "")
    source = re.sub(r"[，、；]?(?:全省陆域|全省土地|全省|全市|陆域|陆地|海域|土地|总)$", "", source)
    source = source.strip("，、；。总 ")
    if source.endswith(name) and len(source) > len(name) + MIN_TEXT_LENGTH:
        source = source[: -len(name)].rstrip("，、；。 ")
    if len(source) < MIN_TEXT_LENGTH:
        source = _clean(desc) or _clean(abstract)
    if len(source) < MIN_TEXT_LENGTH:
        return None
    if len(source) > MAX_TEXT_LENGTH:
        prefix = source[:MAX_TEXT_LENGTH]
        boundary = max(prefix.rfind(mark) for mark in ("。", "！", "？", "；"))
        source = prefix[: boundary + 1] if boundary >= MIN_TEXT_LENGTH else prefix.rstrip("，、；") + "…"
    if not source.endswith(("。", "！", "？", "…")):
        source += "。"
    # Reject a result that clearly belongs to another lemma.
    if _normalise(name) not in _normalise(source) and len(_normalise(name)) < 3:
        return None
    return source


def _fetch(session: requests.Session, name: str) -> dict | None:
    try:
        response = session.get(
            API_URL,
            params={"appid": "379020", "bk_key": name},
            timeout=20,
        )
        if response.status_code != 200:
            return None
        body = response.json()
    except (requests.RequestException, ValueError):
        return None
    title = _clean(str(body.get("title") or body.get("key") or name))
    abstract = _clean(str(body.get("abstract") or ""))
    desc = _clean(str(body.get("desc") or ""))
    description = _stable_summary(abstract, desc, name)
    if not description:
        return None
    source_url = str(body.get("url") or body.get("wapUrl") or "")
    if not source_url:
        source_url = f"https://baike.baidu.com/item/{quote(title)}"
    return {
        "title": title,
        "source_url": source_url,
        "abstract": abstract,
        "description": description,
        "fetched_at": datetime.now().isoformat(timespec="seconds"),
    }


def _load_cache() -> dict:
    if not CACHE_PATH.exists():
        return {}
    try:
        value = json.loads(CACHE_PATH.read_text(encoding="utf-8"))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def _save_cache(cache: dict) -> None:
    CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
    CACHE_PATH.write_text(json.dumps(cache, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _write_override(rows: list[dict]) -> None:
    """Generate the durable catalog override used by application seeding."""
    lines = [
        '"""Public-source province profile overrides. Generated by refresh script."""',
        "",
        "from typing import Final",
        "",
        "PUBLIC_PROVINCE_PROFILES: Final[dict[str, tuple[str, str]]] = {",
    ]
    for item in sorted(rows, key=lambda value: value["name"]):
        lines.append(f"    {item['name']!r}: ({item['title']!r}, {item['description']!r}),")
    lines.extend(["}", ""])
    OVERRIDE_PATH.write_text("\n".join(lines), encoding="utf-8")


def _backup_path() -> Path:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    return BACKUP_DIR / f"province-profiles-before-{datetime.now().strftime('%Y%m%d-%H%M%S')}.json"


def run(*, commit: bool, refresh: bool) -> dict:
    init_database()
    with open_session() as session:
        rows = list(session.scalars(select(ProvinceRow).order_by(ProvinceRow.adcode)))
        before = {row.adcode: {"name": row.name, "tags": list(row.tags or []), "description": row.description} for row in rows}

    cache = {} if refresh else _load_cache()
    session_http = requests.Session()
    session_http.headers.update({"User-Agent": USER_AGENT, "Accept-Language": "zh-CN,zh;q=0.9"})
    for row in rows:
        if row.adcode not in cache or refresh:
            value = _fetch(session_http, row.name)
            cache[row.adcode] = {"name": row.name, "result": value}
    _save_cache(cache)

    matched: list[dict] = []
    unresolved: list[dict] = []
    for row in rows:
        payload = cache.get(row.adcode) or {}
        result = payload.get("result") if isinstance(payload, dict) else None
        if isinstance(result, dict) and result.get("description"):
            matched.append({
                "adcode": row.adcode,
                "name": row.name,
                "title": result["title"],
                "source_url": result["source_url"],
                "description": result["description"],
                "before": row.description,
                "tags": list(row.tags or []),
            })
        else:
            unresolved.append({"adcode": row.adcode, "name": row.name})

    if not commit:
        return {
            "mode": "preview",
            "rows": len(rows),
            "matched": len(matched),
            "unresolved": unresolved,
            "cache_path": str(CACHE_PATH),
            "sample": matched[:8],
        }

    backup_path = _backup_path()
    backup_path.write_text(json.dumps({"created_at": datetime.now().isoformat(timespec="seconds"), "rows": list(before.values())}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    with open_session() as session:
        db_rows = {row.adcode: row for row in session.scalars(select(ProvinceRow))}
        for item in matched:
            db_rows[item["adcode"]].description = item["description"]
        session.commit()
    _write_override(matched)
    return {
        "mode": "commit",
        "rows": len(rows),
        "updated": len(matched),
        "unresolved": unresolved,
        "backup_path": str(backup_path),
        "cache_path": str(CACHE_PATH),
        "override_path": str(OVERRIDE_PATH),
        "sources": [{"name": item["name"], "title": item["title"], "url": item["source_url"]} for item in matched],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--commit", action="store_true")
    parser.add_argument("--refresh-cache", action="store_true")
    args = parser.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print(json.dumps(run(commit=args.commit, refresh=args.refresh_cache), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
